export function translateMessage(source: string, language: Language): string {
    if (language === 'en') return source;
    const normalized = source.trim().replace(/\s+/g, ' ');
    const direct = Object.prototype.hasOwnProperty.call(chineseMessages, normalized) ? chineseMessages[normalized] : undefined;
    if (direct !== undefined) return source.replace(source.trim(), () => direct);
    for (const [pattern, render] of templates) {
        const match = source.trim().match(pattern);
        if (match) return source.replace(source.trim(), () => render(...match.slice(1)));
    }
    return source;
}
